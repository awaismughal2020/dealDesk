"""Seed SAMPLE reference data and one demo user per role. Idempotent; local only.

Refuses to run unless APP_ENV=local. Demo passwords come from the git-ignored .env (generated by
`make init`); nothing here contains a credential.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any

from sqlalchemy import Engine
from sqlalchemy.dialects.postgresql import insert

from dealdesk.adapters.db.models import CaseStudyRow, PastProjectRow, RateCardRow, TeamMemberRow
from dealdesk.adapters.db.session import make_engine, make_session_factory
from dealdesk.adapters.db.users import SqlUserRepository
from dealdesk.adapters.embeddings.factory import build_embedder
from dealdesk.auth.passwords import Argon2Params, PasswordHasher, check_password_policy
from dealdesk.config import Settings, load_settings
from dealdesk.domain.models import UserRole
from dealdesk.ports.embedder import EmbedderPort

SEED_DIR = Path(__file__).resolve().parent.parent / "data" / "seed"
DEMO_ROLES = (UserRole.ADMIN, UserRole.ESTIMATOR, UserRole.APPROVER, UserRole.VIEWER)


def _load(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((SEED_DIR / name).read_text(encoding="utf-8"))
    return data


def _upsert(engine: Engine, model: type[Any], rows: list[dict[str, Any]], key: str) -> None:
    if not rows:
        return
    statement = insert(model).values(rows)
    statement = statement.on_conflict_do_update(
        index_elements=[key],
        set_={column: statement.excluded[column] for column in rows[0] if column != key},
    )
    with engine.begin() as connection:
        connection.execute(statement)


def seed_reference_data(engine: Engine, embedder: EmbedderPort) -> None:
    """Upsert rate card, team, past projects and case studies (with embeddings)."""
    roles = _load("rate_card.json")["roles"]
    _upsert(engine, RateCardRow, [{**r, "is_sample": True} for r in roles], "role")
    members = _load("team.json")["members"]
    _upsert(engine, TeamMemberRow, [{**m, "is_sample": True} for m in members], "id")

    projects = _load("past_projects.json")["projects"]
    project_vectors = embedder.embed([f"{p['title']}. {p['summary']}" for p in projects])
    case_vectors = embedder.embed(
        [f"{p['case_study']['title']}. {p['case_study']['summary']}" for p in projects]
    )
    _upsert(
        engine,
        PastProjectRow,
        [
            {
                "id": p["id"],
                "title": p["title"],
                "sector": p["sector"],
                "summary": p["summary"],
                "actual_hours": p["actual_hours"],
                "embedding": vector,
                "is_sample": True,
            }
            for p, vector in zip(projects, project_vectors, strict=True)
        ],
        "id",
    )
    _upsert(
        engine,
        CaseStudyRow,
        [
            {
                "id": p["case_study"]["id"],
                "project_id": p["id"],
                "title": p["case_study"]["title"],
                "summary": p["case_study"]["summary"],
                "embedding": vector,
                "is_sample": True,
            }
            for p, vector in zip(projects, case_vectors, strict=True)
        ],
        "id",
    )


def seed_demo_users(users: SqlUserRepository, hasher: PasswordHasher) -> list[str]:
    """Create or refresh one demo user per role from DEMO_<ROLE>_EMAIL/_PASSWORD."""
    seeded = []
    for role in DEMO_ROLES:
        prefix = f"DEMO_{role.value.upper()}"
        email = os.environ.get(f"{prefix}_EMAIL", "")
        password = os.environ.get(f"{prefix}_PASSWORD", "")
        if not email or not password:
            print(f"seed: {prefix}_EMAIL/_PASSWORD not set; run `make init`", file=sys.stderr)
            raise SystemExit(2)
        check_password_policy(password, email=email)
        existing = users.get_by_email(email)
        if existing is None:
            users.create(
                email=email,
                display_name=f"Demo {role.value.title()} (SAMPLE)",
                role=role,
                password_hash=hasher.hash(password),
            )
        elif not hasher.verify(existing.password_hash, password) or existing.role is not role:
            users.update(
                existing.id, password_hash=hasher.hash(password), role=role, is_active=True
            )
        seeded.append(f"{role.value}: {email}")
    return seeded


def main(settings: Settings | None = None) -> None:
    """Seed everything. Exits non-zero outside APP_ENV=local."""
    settings = settings or load_settings()
    if not settings.is_local:
        print("seed: refusing to run because APP_ENV is not 'local'", file=sys.stderr)
        raise SystemExit(1)
    engine = make_engine(settings.database_url.get_secret_value(), pool_size=2)
    try:
        seed_reference_data(engine, build_embedder(settings))
        hasher = PasswordHasher(
            Argon2Params(
                settings.argon2_time_cost,
                settings.argon2_memory_cost_kib,
                settings.argon2_parallelism,
            )
        )
        users = seed_demo_users(SqlUserRepository(make_session_factory(engine)), hasher)
    finally:
        engine.dispose()
    print("seed: SAMPLE reference data upserted (8 roles, 10 people, 5 projects, 5 case studies)")
    print("seed: demo users ready -> " + ", ".join(users))
    print("seed: passwords are the DEMO_*_PASSWORD values in your .env")


if __name__ == "__main__":
    main()
